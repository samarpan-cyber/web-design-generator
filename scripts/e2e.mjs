// E2E smoke test: node scripts/e2e.mjs [baseUrl] [profile.json]. Mocks /api/analyze with a saved profile.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:3111';
const profile = JSON.parse(fs.readFileSync(process.argv[3] || '/tmp/claude-0/shots/profile.json', 'utf8'));
const out = process.env.OUT || '/tmp/claude-0/e2e'; fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 1500, height: 950 } });
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error' && !/Failed to load|net::/.test(m.text())) errs.push(m.text()); });
await page.route('**/api/analyze', r => r.fulfill({ json: { ok: true, profile } }));
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) errs.push('assert: ' + m); };
await page.goto(base); await page.waitForSelector('.lead');
ok(await page.locator('.lead').count() === 19, '19 leads rendered');
await page.screenshot({ path: out + '/1-welcome.png' });
await page.fill('#input', 'Temple Electromagnetics'); await page.press('#input', 'Enter');
await page.waitForSelector('#grid .card', { timeout: 15000 }); await page.waitForTimeout(3500);
ok(await page.locator('#grid .card').count() === 5, '5 design cards');
ok(/Done!/.test(await page.locator('.msg.bot').last().innerText()), 'bot summary shown');
const loaded = await page.$$eval('#grid iframe', fs => fs.filter(f => f.srcdoc && f.srcdoc.length > 5000).length); ok(loaded >= 1, 'iframes rendered lazily: ' + loaded);
await page.screenshot({ path: out + '/2-results.png' });
await page.click('[data-t=light]'); await page.waitForTimeout(500);
await page.screenshot({ path: out + '/3-light.png' });
await page.click('[data-t=dark]'); await page.click('[data-open="3"]'); await page.waitForTimeout(1200);
ok(await page.locator('#viewer').isVisible(), 'viewer opens');
ok((await page.innerText('#vName')).includes('Aurora'), 'viewer shows 4th concept');
await page.click('#devSeg [data-d="390px"]'); await page.waitForTimeout(700); await page.screenshot({ path: out + '/4-viewer-mobile.png' });
const fr = page.frameLocator('#vFrame');
await fr.locator('[data-quote]').first().click({ force: true }); await fr.locator('[data-quote-open]').first().click({ force: true }); await page.waitForTimeout(700);
ok(await fr.locator('#wdg-q.open').count() === 1, 'quote basket opens inside design');
await page.keyboard.press('Escape'); await page.keyboard.press('Escape'); await page.waitForTimeout(300); ok(await page.locator('#viewer').isHidden(), 'Esc closes viewer');
await page.click('#editBtn'); await page.fill('[name=name]', 'Edited Co'); await page.click('button[value=ok]'); await page.waitForTimeout(800);
ok((await page.innerText('#resTitle')) === 'Edited Co', 'edit dialog applies');
const dl = page.waitForEvent('download'); await page.click('[data-dl="1"]'); const d = await dl; ok(/bento\.html$/.test(d.suggestedFilename()), 'download filename ' + d.suggestedFilename());
await b.close();
console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'ALL GOOD');
